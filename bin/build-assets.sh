#!/usr/bin/env bash
#
# Build the theme's CSS and JavaScript.
#
# Source lives in small, single-purpose files:
#   assets/css/src/*.css  ->  assets/css/main.css
#   assets/js/src/*.js    ->  assets/js/main.js
#
# Files are joined in filename order (hence the numeric prefixes); CSS is also minified. The output is
# committed so the theme works without a build step on the server; never edit
# the built files by hand.
#
# Usage: bin/build-assets.sh [output-dir]
#   output-dir  optional; build there instead of into assets/ (used by check.sh).

set -euo pipefail

THEME_DIR="$(cd "$(dirname "$0")/.." && pwd)"
OUT_DIR="${1:-$THEME_DIR/assets}"

# build <extension> <source-dir> <output-file>
build() {
  local ext="$1" src="$2" out="$3" body

  mkdir -p "$(dirname "$out")"
  body="$(
    for file in "$src"/*."$ext"; do
      echo
      cat "$file"
    done
  )"

  {
    echo "/* GENERATED by bin/build-assets.sh from ${src#"$THEME_DIR"/}/*.$ext — do not edit. */"
    if [ "$ext" = "css" ]; then
      # Stylesheets are minified (bin/minify-css.py); the readable source stays in assets/css/src.
      printf '%s\n' "$body" | python3 "$THEME_DIR/bin/minify-css.py"
    else
      printf '%s\n' "$body"
    fi
  } > "$out"
}

build css "$THEME_DIR/assets/css/src" "$OUT_DIR/css/main.css"
build js  "$THEME_DIR/assets/js/src"  "$OUT_DIR/js/main.js"

echo "Built $OUT_DIR/css/main.css and $OUT_DIR/js/main.js"
